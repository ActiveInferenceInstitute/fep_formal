"""Generate static aliases for the runtime legacy module identities."""

from __future__ import annotations

import argparse
import ast
import subprocess
import sys
from pathlib import Path


def expected(root: Path) -> dict[Path, str]:
    source = root / "src/fep_formal"
    if not (source / "__init__.py").is_file():
        raise ValueError(f"Missing canonical package: {source}")
    target = root / "src/fep_lean"
    outputs = {target / "py.typed": ""}
    for path in sorted(source.rglob("*.py")):
        relative = path.relative_to(source)
        parts = list(relative.with_suffix("").parts)
        if parts[-1] == "__init__":
            parts.pop()
        module = ".".join(["fep_formal", *parts])
        tree = ast.parse(path.read_text(encoding="utf-8"))
        exports: list[str] | None = None
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets
            ):
                value = ast.literal_eval(node.value)
                if not isinstance(value, (list, tuple)) or not all(
                    isinstance(x, str) for x in value
                ):
                    raise ValueError(f"Invalid exports: {path}")
                exports = list(value)
        text = "# Generated by specs/identity-cutover/generate_legacy_stubs.py.\n"
        if exports is None:
            text += f"from {module} import *  # noqa: F403 - preserve canonical public exports\n"
        else:
            for name in sorted(exports):
                text += f"from {module} import {name} as {name}\n"
            text += f"\n__all__ = {exports!r}\n"
        if relative.as_posix() == "__init__.py":
            text += "from fep_formal import __version__ as __version__\n"
        destination = target / relative.with_suffix(".pyi")
        ordered = subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "check",
                "--isolated",
                "--select",
                "I",
                "--fix",
                "--stdin-filename",
                str(destination),
                "-",
            ],
            input=text,
            text=True,
            capture_output=True,
            check=True,
            timeout=30,
        )
        formatted = subprocess.run(
            [
                sys.executable,
                "-m",
                "ruff",
                "format",
                "--isolated",
                "--stdin-filename",
                str(destination),
                "-",
            ],
            input=ordered.stdout,
            text=True,
            capture_output=True,
            check=True,
            timeout=30,
        )
        outputs[destination] = formatted.stdout
    return outputs


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument(
        "--root", type=Path, default=Path(__file__).resolve().parents[2]
    )
    args = parser.parse_args()
    outputs = expected(args.root)
    stale = set((args.root / "src/fep_lean").rglob("*.pyi")) - outputs.keys()
    if stale:
        raise ValueError(f"Unexpected legacy stubs: {sorted(stale)}")
    drift = []
    for path, content in outputs.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if drift:
        print("Legacy stub drift: " + ", ".join(drift))
        return 1
    print(f"Legacy stub files: {len(outputs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
