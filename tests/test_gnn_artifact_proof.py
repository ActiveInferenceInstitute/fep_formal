def test_symmetric_fixture_extracts_exact_tables() -> None:
    tables = extract_pymdp_tables(SYMMETRIC_FIXTURE.read_text(encoding="utf-8"))
    assert tables.source_sha256 == sha256_file_strict(SYMMETRIC_FIXTURE)
    for name, shape in DISCRETE_BOOL_SHAPES.items():
        assert tables.table(name).shape == shape, name
    a = tables.table("A_data")
    for outcome in range(2):
        for state in range(2):
            assert a.get((outcome, state)) == Fraction(1, 2)
    e = tables.table("E_data")
    assert e.get((0,)) == Fraction(1, 4)
    assert e.get((1,)) == Fraction(3, 4)


def test_asymmetric_fixture_extracts_exact_tables() -> None:
    tables = extract_pymdp_tables(ASYMMETRIC_FIXTURE.read_text(encoding="utf-8"))
    a = tables.table("A_data")
    assert a.get((0, 0)) == Fraction(1, 4)
    assert a.get((0, 1)) == Fraction(1, 2)
    assert a.get((1, 0)) == Fraction(3, 4)
    assert a.get((1, 1)) == Fraction(1, 2)
    b = tables.table("B_data")
    assert b.get((0, 0, 0)) == Fraction(1, 4)
    assert b.get((1, 0, 0)) == Fraction(3, 4)
    assert b.get((0, 1, 0)) == Fraction(3, 4)
    assert b.get((1, 1, 0)) == Fraction(1, 4)
    assert b.get((0, 0, 1)) == Fraction(1, 2)
    assert b.get((0, 1, 1)) == Fraction(1, 8)
    assert b.get((1, 0, 1)) == Fraction(1, 2)
    assert b.get((1, 1, 1)) == Fraction(7, 8)
    assert tables.table("C_data").get((0,)) == Fraction(1, 4)
    assert tables.table("C_data").get((1,)) == Fraction(3, 4)
    assert tables.table("E_data").get((0,)) == Fraction(3, 8)
    assert tables.table("E_data").get((1,)) == Fraction(5, 8)


