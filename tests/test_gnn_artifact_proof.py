def test_regeneration_does_not_bypass_stored_digest() -> None:
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))
    key = "generated/probe_symmetric.lean"
    stored = manifest["generated"][key]
    tampered_stored = "1" * 64
    assert tampered_stored != stored
    regenerated = {key: stored}  # regeneration agrees with on-disk bytes
    tampered_text = (
        json.dumps(
            {**manifest, "generated": {**manifest["generated"], key: tampered_stored}},
            sort_keys=True,
            indent=2,
        )
        + "\n"
    )
    problems = manifest_mismatches(
        tampered_text,
        repo_root=PROJECT_ROOT,
        slice_root=SLICE,
        regenerate=regenerated,
    )
    assert any(
        problem.startswith(f"{key}: on-disk ") and "manifest 1111" in problem
        for problem in problems
    )


