def _lake_executable() -> str | None:
    lake = shutil.which("lake")
    if lake is None:
        return None
    if (
        not (LEAN_ROOT / "lakefile.lean").exists()
        and not (LEAN_ROOT / "lakefile.toml").exists()
    ):
        return None
    return lake


def _compile_probe(path: Path) -> subprocess.CompletedProcess[str]:
    return run_lean_probe(path, import_root=IMPORT_ROOT, cwd=LEAN_ROOT, timeout_s=900)


def _runner_body(*lines: str) -> str:
    body = "".join(line + "\n" for line in lines)
    return (
        "from __future__ import annotations\n\n\n"
        "def main() -> int:\n"
        f"{body}"
        "    return 0\n"
    )


def _base_body() -> list[str]:
    return [
        "    A_data = [[0.5, 0.5], [0.5, 0.5]]",
        "    B_data = [[[0.5, 0.5], [0.5, 0.5]], [[0.5, 0.5], [0.5, 0.5]]]",
        "    C_data = [0.5, 0.5]",
        "    D_data = [0.5, 0.5]",
        "    E_data = [0.25, 0.75]",
    ]


def _tables(source: str) -> PymdpArtifactTables:
    return extract_pymdp_tables(source, source_name="<test runner>")


def _expect_rejection(source: str, reason: str) -> None:
    with pytest.raises(ArtifactProofError) as excinfo:
        _tables(source)
    assert excinfo.value.reason == reason, excinfo.value.detail


