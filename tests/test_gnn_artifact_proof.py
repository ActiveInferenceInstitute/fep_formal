def test_asymmetric_transition_distinguishes_every_axis_permutation() -> None:
    from itertools import permutations, product

    table = _tables(ASYMMETRIC_FIXTURE.read_text()).table("B_data")
    for order in permutations(range(3)):
        if order != (0, 1, 2):
            assert any(
                table.get(index) != table.get(tuple(index[axis] for axis in order))
                for index in product(range(2), repeat=3)
            ), f"asymmetric fixture hides axis permutation {order}"


